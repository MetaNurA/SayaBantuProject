class PartnerJobModel {
  final String title;
  final String category;
  final String description;
  final String location;
  final String time;
  final String price;
  final int bidderCount;
  final String image;

  PartnerJobModel({
    required this.title,
    required this.category,
    required this.description,
    required this.location,
    required this.time,
    required this.price,
    required this.bidderCount,
    required this.image,
  });
}